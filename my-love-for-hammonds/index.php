			<p align="justify">When I was 12 years old, I decided to pursue music as my life’s profession. I started playing small parties and weddings when I was 13 years old. My parents bought me a little portable organ and I also had a theatre organ for the home. I so often wondered why my music didn’t sound as good as the music I heard on the radio. I thought it must have been my playing, but then one day, an older friend and fellow musician invited me to hear a professional organist who was playing nearby. He was trying to convince me to upgrade my keyboard setup. I went to hear his friend and the sound of his instrument sent chills up and down my body. I went over to his instrument after a break and discovered it was a Hammond organ with an external Leslie. I asked if I could play it. That’s when I discovered it wasn’t my playing but it was the instrument I was playing.</p>
<p align="justify">At the age of 14, I fell in love with the sound of what is now called the Vintage Hammond Sound. At the age of 15, I begged and borrowed every penny I could and bought a C-3 Hammond Organ and 122 Leslie. At age 16, I bought a van and started playing professionally in the Philadelphia area. That Hammond went everywhere! It was on an ocean cruiser; it was all over the country; and it even fell over in a truck in New Jersey and the keyboard popped out! I called a friend and he came and helped me pop the keyboard back in and it was playing that night. We had to super glue a key back on, but that was it! That organ stayed in trucks in the winter, suffered the heat of the summer, the humidity of spring, and the abuse of road managers. It was as far north as Canada and as far south as Florida.</p>
<p align="justify">In 1975 I went to college I was an Organ/Piano major; and again, that Hammond became a workhorse for my practice instrument. A friend of mine helped me tear a wall out of our little 10′ x 55′ trailer so we could fit my Hammond into a spare bedroom. After graduating from college, I worked for a large music retailer for quite a few years. Out of roughly 10 sales people, I sold half of the Hammond organ consoles in the company. The owner later made me director of church organ sales. That year, I broke all sales records in the company, mostly from my Hammond Organ Sales. I left that company in 1988 and established my own Piano Service Business, but have never lost my love for the Hammond Organ. For years I recommended only the older vintage Hammond Organs because the technology just wasn’t advanced enough and economics would not allow for the reproduction of the vintage tone wheel sound. However, I can honestly say that with the advancement of digital technology the new Hammonds have finally done their homework and are now giving musicians an alternative to have the great sound of a vintage B-3, C-3 or A-100. The new Hammond organs have the Midi and digital features that are a must for any serious musician and in a side by side comparison it is hard to tell the difference.</p>
<p align="justify">A while back my old boss called and asked me if I wanted to buy the remaining inventory, equipment and truck of my old company, because he was retiring.  With the closing of his store this left a void in our area for a Piano Organ retailer, and he and others encouraged me to fill that void. With his help this has led to the opening of Piano Organ Depot of Northeastern PA. In fact he was the one that even picked out the name for our company.  We are excited about being able to now offer both vintage Refurbished Hammond Organs and the new Digital XK-3 system and B-3 organs as well as Leslies and Home and Church Organs to homes, churches, and professional musicians. In our showroom you can play the new Vast technology Hammonds along side of a vintage Hammond. You can compare the two and decide for yourself which you like. We are here to help the those who want to hear and play only the best get the best sound in their purchase of a New or vintage Hammond Organ.</p>
