HAMMOND ORGANS &amp; LESLIES</h4>
<p align="justify"><strong> ORGANS THAT WE DO NOT BUY:</strong>   We do not buy later model Hammond Organs, i.e. 1970 – 1990 vintage organs. We do not buy Hammond spinet organs. We will if within a reasonable distance sometimes remove these free of charge if they can be used for parts or restored. However, we cannot offer any money for these. Most latter model organs we do not take at all. For the most part even when we take these in on trade we just break even by time we service them and move them.</p>
<p align="justify">Concerning Giving an appraisal Of the Value of your organ It is impossible for us to tell you what the value of your organ is without seeing it, and if you are too far for us to offer this service we will not be able to help you. Many people call from around the country asking what is their organ worth. Without seeing the organ we cannot tell you. Therefore when we buy vintage organs sight unseen we have to assume we have to rebuild them. Also, many people look and see what dealers are selling vintage Hammond organs for and assume that their organ is worth the same amount of money. Most people that are selling these vintage organs are doing so because it has not been played or serviced for many years. Realize that every vintage Hammond Organ is now in the neighborhood of 40 – 60 years old. They all need service. Many times from not being played for years, the tone generators lock up, and we need to go in and unfreeze tone wheels, most need capicitros replaced and some need tone generators retuned. Remember if you had a 40 – 60 year old Allen, Rogers, Baldwin, Gulbranson or any other electronic organ it would be worthless. The only reason a vintage Hammond is worth anything is because it can be brought back to life. However, it takes work to bring them back to life. Therefore we cannot give you the retail prices we sell organs for after they have been serviced. Don’t waist our time and even call us if you are trying to sell your organ at retail pricing. We cannot give you that amount of money for your organ. Every vintage Hammond needs some service. Also the further away you are from us the more we have to factor in the shipping.</p>
<p align="justify"><strong>THE VINTAGE HAMMONDS THAT WE ARE INTERESTED IN BUYING:</strong> At <a title="Piano Depot in Olyphant, PA" href="/"><u>Piano Depot</u></a>, we are interested in buying Hammond B model organs B-3’s B-2’s and even some BV’s.. We would be interested in C-3’s, c-2’s CV’s D-100’s A-100’s, and RT3’s and RT-2’s. We are not interested in the E-100’s H-100’s and the 70 – 80 vintage Hammonds.</p>
<p>We also are looking for leslie tone cabinets, Model 122’s 145’s and 147’s, the lessor leslies which we often pay less for are the 21H and Models 251, 125, 45, 25, 247, 245, 225, 222, 31H, etc.. Most solid state leslies we are not interested in….</p>
