<h2 align="justify">Let me share an amusing story about my wife’s piano teacher. When she was studying piano as a little girl the piano teacher used to slap her hands with a little conductors wand whenever she made a mistake. Week after week she dreaded getting hit with that little stick.</h2>
<h2 align="CENTER"><img decoding="async" loading="lazy" src="https://www.pianoorgandepot.com/JPG/Conductor1.jpg" alt="" width="150" height="275" border="1"></h2>
<h2 align="justify">One day her teacher was called out of the studio by his wife. It was near the end of her lesson. He left the room and there sat that diabolical little stick. She looked this way and that way quickly grabbed the stick, opened the lid and threw it into the piano.</h2>
<h2 align="CENTER"><img decoding="async" loading="lazy" src="https://www.pianoorgandepot.com/JPG/LittleGirl-Stick.jpg" alt="" width="245" height="312" border="1"></h2>
<h2>When the teacher came back he took a few minutes to write out her assignments for the next week and said good bye to her and she left. She breathed a sign of relief and chuckled to herself.</h2>
<h2 align="CENTER"><img decoding="async" loading="lazy" src="https://www.pianoorgandepot.com/JPG/Little-Girl.jpg" alt="" width="140" height="350" border="1"></h2>
<h2>The next week when my wife showed up for her lesson she noticed a brand new piano in his studio.</h2>
<h2 align="CENTER"><img decoding="async" loading="lazy" src="https://www.pianoorgandepot.com/JPG/Shinny-Piano.jpg" alt="" width="355" height="300" border="1"></h2>
<h2 align="justify">She said to her teacher, “Mr. Perro, what happened to your old piano. ” He said to her, “it was a funny thing but after our lesson last week that piano started making the most awful noises. I decided to trade it in and get a new piano.”  My wife was very quiet.  Then as he started the lesson. He said to her, “by the way have you seen my stick I seem to have misplaced it.”</h2>
<h2>This is why you should buy a new piano from a company that knows both sales and service or you may always get the short end of the stick!</h2>
