	<h2>Description</h2>

<p></p><center><iframe loading="lazy" title="YouTube video player" src="https://www.youtube.com/embed/OeMab58WDF4" width="640" height="525" frameborder="0" allowfullscreen="allowfullscreen"><span style="display: inline-block; width: 0px; overflow: hidden; line-height: 0;" data-mce-type="bookmark" class="mce_SELRES_start">﻿</span><span style="display: inline-block; width: 0px; overflow: hidden; line-height: 0;" data-mce-type="bookmark" class="mce_SELRES_start">﻿</span></iframe></center><img decoding="async" class="img-responsive aligncenter" src="https://usa.yamaha.com/files/013_B_YUS_Series_1200_480_1200x480_11e95e6f84e370fa495f56bbf7ca20f5.jpg" alt="">
<p>The YUS Series are superbly crafted instruments with inspiringly rich sound and delicate balance. The simplicity of the cabinet gives superb acoustics to the subtlest note, and specially designed hammers provide rich tone. And the simple, meticulous design rounds out a piano that enhances the performance of professional and home pianists alike.</p>
<h3></h3>
<p> </p>
<h3 style="text-align: center;">The Finest Wood</h3>
<p><img decoding="async" class="aligncenter" src="https://www.yamaha.com/us/pianos/images/wood-features2.jpg" alt="Close up of ribs and crown elements in a piano that is in process of being built."></p>
<div class="uk-margin">The top ten percent of solid spruce from around the world is hand selected from our Kitami Mill in Hokkaido, Japan for the YUS piano soundboards. The crown is reinforced with full-length, solid spruce ribs for a refined, dynamic tone expected in a grand piano.</div>
<h3></h3>
<p> </p>
<h3 style="text-align: center;">Superior Voicing and Regulation</h3>
<div>
<p><img decoding="async" class="aligncenter" src="https://www.yamaha.com/us/pianos/images/hammer-feature3.jpg" alt="A closeup of a man's hands as he uses a pair of pliers to adjust hammers."></p>
<div class="uk-margin">YUS pianos are voiced and regulated by master technicians in Kakegawa, Japan to ensure that everything, from the strike of the hammers to the weight of the keys and depth of the key travel, are reminiscent of the finest grand piano.</div>
</div>
<h3></h3>
<p> </p>
<h3 style="text-align: center;">Hand-Wound European Brass Strings</h3>
<div>
<p><img decoding="async" class="aligncenter" src="https://www.yamaha.com/us/pianos/images/bass-strings.jpg" alt="Closeup of gloved hands wrapping a piano wire that is taut."></p>
<div class="uk-margin">Yamaha artisans wind each bass string by hand to the exacting standards and sound profile of every YUS piano at our factory in Kakegawa, Japan.</div>
</div>
<div></div>
<p> </p>
<h3 style="text-align: center;">Concert Quality Hammer Felt</h3>
<div>
<p><img decoding="async" class="aligncenter" src="https://www.yamaha.com/us/pianos/images/u-hammers.jpg" alt="View of a row of hammers n process of being installed in an upright piano."></p>
<div class="uk-margin" style="text-align: left;">We took everything we learned from crafting the hammers of our flagship CFX concert grand and redesigned the hammers of the YUS to bring out powerful, nuanced tones on an upright piano.</div>
</div>
<div></div>
<p> </p>
<h3 style="text-align: center;">Room Filling Sound</h3>
<div>
<p><img decoding="async" class="aligncenter" src="https://www.yamaha.com/us/pianos/images/YCA18-YUS5-015_0067-V3.jpg" alt="A man smiling as he plays from sheet music on a Yamaha upright piano in his living room."></p>
<div class="uk-margin">Each YUS piano features a proprietary Yamaha tone escapement system that helps provide the clarity of tone and power that is rarely found in an upright.</div>
</div>
<h3></h3>
<p> </p>
<h3 style="text-align: center;">Back Posts, Forward Thinking</h3>
<div>
<p><img decoding="async" class="aligncenter" src="https://www.yamaha.com/us/pianos/images/feature-backpost.jpg" alt="The back of an upright piano with view of backposts supporting board."></p>
<div class="uk-margin">Years of cutting-edge research, including our proprietary wood-drying process, result in durable back posts that maintain their shape, strength and resonance for years to come.</div>
</div>
<div></div>
<p> </p>
<h3 style="text-align: center;">Advanced V-Pro Frame</h3>
<div>
<p><img decoding="async" class="aligncenter" src="https://www.yamaha.com/us/pianos/images/inside-yus.jpg" alt="An upright piano with lid open displaying interior."></p>
<div class="uk-margin">Yamaha was the first company to use an advanced Vacuum Shield Mold casting technology called V-Pro to create a stronger, lighter, more durable frame. Every YUS Series piano features a full-perimeter frame built to our exacting specifications at our Iwata Forge in Japan.</div>
</div>
<div></div>
<p> </p>
<h3 style="text-align: center;">The Worlds First Aluminum Action Rail</h3>
<div>
<p><img decoding="async" class="aligncenter" src="https://www.yamaha.com/us/pianos/images/action-rail.jpg" alt="Interior of upright with closeup of key mechanisms."></p>
<div class="uk-margin">Often copied but never equaled, the patented Yamaha aluminum action rail helps assure our piano keyboards are resistant to tiny fluctuations in humidity and temperature over time.</div>
</div>
