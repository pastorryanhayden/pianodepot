	<h2>Description</h2>

<h3 style="text-align: center;">Demonstrating U1 TransAcoustic</h3>
<p></p><center><iframe loading="lazy" title="YouTube video player" src="https://www.youtube.com/embed/OdshxsRsclI" width="1200" height="675" frameborder="0" allowfullscreen="allowfullscreen"></iframe><center></center></center> 
<h3 style="text-align: center;">The Sound Board is Your Amplifier</h3>
<p><img decoding="async" class="hero-cover" src="https://www.yamaha.com/us/pianos/images/ta-hero.jpg" srcset="https://www.yamaha.com/us/pianos/images/ta-hero-4k.jpg 4x"></p>
<p>When a hammer strikes a string, all elements of the acoustic piano resonate together to amplify the unique sound of the instrument. TransAcoustic Technology uses these acoustic elements to bring digital sounds to life, allowing you to adjust the volume and experience the piano in a whole new way.</p>
<h3 style="text-align: center;">Let There Be Light Transducers</h3>
<p><img decoding="async" class="el-image" src="https://www.yamaha.com/us/pianos/images/02-LetThereBeLightTransducers.jpg"></p>
<div class="uk-margin">We created a state-of-the-art, ultra-light transducer that can turn digital sounds into vibrations and apply them directly to the soundboard. All without sacrificing the remarkable acoustic tone you’ve come to expect from a Yamaha piano.</div>
<h3 style="text-align: center;">Every Nuance, Every Note</h3>
<p><img decoding="async" class="el-image" src="https://www.yamaha.com/us/pianos/images/01-AMoreHumanPerformance.jpg"></p>
<div class="uk-margin">Our patented non-contact Optical Sensor System continuously measures the movement, timing, depth and force of every key attack and release to faithfully capture and reproduce the subtle nuances of your performance.</div>
<h3 style="text-align: center;">A Concert Hall In Your Headphones</h3>
<p style="text-align: left;">By day it’s a world-renowned acoustic piano. By night, the neighbors won’t hear a thing. SILENT Piano™ puts the sound and presence of the world’s finest concert grands in your headphones. Simply switch TransAcoustic piano into SILENT mode and our digital technology reproduces the acoustic tones, nuanced colors and resonance so faithfully you’ll almost forget you’re wearing headphones.</p>
<h3></h3>
<h3 style="text-align: center;">Pure, Natural Sound</h3>
<p><img decoding="async" class="el-image" src="https://www.yamaha.com/us/pianos/images/05-PureNaturalSound.jpg"></p>
<div class="uk-margin">When in SILENT mode, three proprietary technologies work together to emulate the natural feeling and sound of an acoustic piano in your headphones. Virtual Resonance Modeling (VRM) recreates the resonance of the strings, soundboard and case. Our advanced binaural sampling method simulates the sound you hear when sitting at the piano. Smooth Release Technology models the subtle interactions of the piano strings with the damper.</div>
<h3 style="text-align: center;">Plays Well With Others</h3>
<p>It’s easy to connect TransAcoustic with your audio and MIDI devices for recording, live sound or broadcast and it works seamlessly with computers, mixing boards and Bluetooth®-enabled devices.</p>
<h3 style="text-align: center;">Overview</h3>
<p>Fully integrated TransAcoustic system<br>
Patented dual-transducer technology<br>
Non-contact optical sensor system<br>
Key Sensor type: Continuous grayscale<br>
Hammer Sensor type: Shutter type<br>
Damper Pedal Sensor type: Continuous grayscale<br>
Shift/Soft Sensor type: On/Off detection system<br>
Sostenuto Sensor type: On/Off detection system (for models with sostenuto)<br>
Motorized muting system with Quick Escape mechanism (grands only)<br>
20 playable digital voices<br>
Binaural CFX Concert Grand voice for headphones<br>
480 ensemble voices with 12 Drum Kits<br>
256-note polyphony<br>
Recording formats: Standard MIDI, Audio WAV<br>
Supported file formats: Standard MIDI, WAV<br>
Compatible storage media: USB Flash Memory (up to 64GB)<br>
MIDI connectivity: 5-pin MIDI IN/OUT, USB TO HOST<br>
Audio connectivity: Stereo audio IN x1 (mini stereo), analog audio OUT x 2 (TS), Bluetooth<br>
Headphone connectivity: 1/8” mini stereo x 2<br>
Data connectivity: USB TO DEVICE x 1, UD-WL01 (WiFi)<br>
Smart Pianist app compatibility<br>
<em><strong>Available models: U1, YUS1, YUS3, YUS5, GC1, C1X, C3X</strong></em></p>
