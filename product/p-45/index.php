	<h2>Description</h2>

<p></p><center><iframe loading="lazy" title="YouTube video player" src="https://www.youtube.com/embed/BEPKPpDGvrU" width="1130" height="635" frameborder="0" allowfullscreen="allowfullscreen"></iframe></center>
<div class="mbr-col-sm-12 mbr-col-md-12 mbr-col-lg-6 img-text_col-text">
<div class="wrapper">
<h1></h1>
<h1 class="cover-underline" style="text-align: center;">Key feel provides an authentic piano-playing experience.</h1>
<p class="description">The P-45 features a graded hammer standard (GHS) keyboard. The feel of the keyboard gradually changes according to the register, so that it feels heavier when playing bass parts and lighter when playing treble parts. The piano also features a keyboard with a natural feel, with black keys that feature a matte finish for authentic piano playing close to that of an acoustic piano.</p>
</div>
<div class="mbr-col-sm-12 mbr-col-md-12 mbr-col-lg-6 img-text_col-text">
<div class="wrapper">
<h1 class="cover-underline" style="text-align: center;">Recreates the real reverberation of a grand piano</h1>
<p class="description">The P-45 has improved on the traditional AWM synthesis to deliver real piano sounds. AWM is a technology that uses digital recordings of sources, such as actual instruments, and allows you to enjoy grand piano reverberation wherever you are.</p>
</div>
<div class="mbr-col-sm-12 mbr-col-md-12 mbr-col-lg-6 img-text_col-text">
<div class="wrapper">
<h1 class="cover-underline" style="text-align: center;">Compact and light design provides for easy transportation.</h1>
<p class="description">Slim and stylish form With a depth of less than 30 cm, the instrument requires little space, and at only 11.5 kg—with its speaker attached—it can be easily moved anywhere in your home or even used for performance outside.</p>
<p><img decoding="async" class="img-responsive aligncenter" src="https://usa.yamaha.com/files/features_03_1a0516e66935de3da609909eda512bdc.jpg" alt=""></p>
<div class="mbr-col-sm-12 mbr-col-md-12 mbr-col-lg-6 img-text_col-text">
<div class="wrapper">
<h1 class="cover-underline" style="text-align: center;">Simple operation with a single button</h1>
<p class="description">Various P-45 settings can be changed with a single button. Hold down the “GRAND PIANO/FUNCTION” button and press the keyboard to change timbres, play demo sources, configure the metronome, and more.</p>
